#: Action mix for the trading phase. The *order* of these pairs is part of the
#: generator contract: reordering them changes which action a given draw picks
#: and therefore changes every dataset.
_ACTION_WEIGHTS: tuple[tuple[str, int], ...] = (
    ("TICK", 25),
    ("OPEN", 35),
    ("CLOSE", 30),
    ("INCREASE", 10),
)

_CLOSE_KIND_WEIGHTS: tuple[tuple[str, int], ...] = (("FULL", 60), ("PARTIAL", 40))

#: One pip on a 5-digit FX pair.
_SPREAD = Decimal("0.00010")

#: Commission is linear in volume, which makes the golden vector in section 3.4
#: fall out exactly: 0.50 lots -> -2.50.
_COMMISSION_PER_LOT = Decimal("-5.00")

#: Maximum fractional distance a price may walk from its anchor.
_PRICE_BAND = Decimal("0.20")
_TICK_DELTA = Decimal("0.00050")
_TICK_GRID = Decimal("0.00001")

_MAX_OPEN_VOLUME = Decimal("1.00")
_MAX_INCREASE_VOLUME = Decimal("0.50")
_SWAP_LOW = Decimal("-1.00")
#: Deliberately reaches above zero: a positive swap is legal (a rebate) and
#: WF-022 requires the sign to be carried through rather than normalized.
_SWAP_HIGH = Decimal("0.20")
_SWAP_GRID = Decimal("0.10")

_ANCHOR_PRICES: dict[str, Decimal] = {
    "EURUSD": Decimal("1.10000"),
    "GBPUSD": Decimal("1.27000"),
    "AUDUSD": Decimal("0.65000"),
}
_DEFAULT_ANCHOR = Decimal("1.00000")


@dataclass(frozen=True, slots=True)
class ScenarioSpec:
    """Everything that determines a dataset.

    ``digest`` covers exactly these fields. Two runs agree on their canonical
    content digest if and only if they agree on this spec, the generator
    version and the accounting policy version.
    """

    scenario_name: str
    seed: int
    start_virtual_time: datetime
    account_count: int
    deal_count: int
    max_open_positions: int
    symbols: tuple[str, ...]
    initial_balance_usd: Decimal
    generator_version: str = GENERATOR_VERSION
    execution_mode: str = "bulk_generate"
    fault_profile: str = "none"

    def to_canonical(self) -> dict[str, Any]:
        return {
            "scenario_name": self.scenario_name,
            "seed": self.seed,
            "start_virtual_time": format_timestamp(self.start_virtual_time),
            "account_count": self.account_count,
            "deal_count": self.deal_count,
            "max_open_positions": self.max_open_positions,
            "symbols": list(self.symbols),
            "initial_balance_usd": acc.format_decimal(self.initial_balance_usd),
            "generator_version": self.generator_version,
            "execution_mode": self.execution_mode,
            "fault_profile": self.fault_profile,
        }

    @property
    def digest(self) -> str:
        return digest_of(self.to_canonical())


def validate_spec(spec: ScenarioSpec, *, limits: Any) -> None:
    """Validate a spec against configured bounds (WF-005, WF-006, WF-007).

    ``limits`` is the :class:`~simulator.settings.Settings` instance; it is
    typed loosely to keep this module free of a settings import cycle.
    """
    if spec.generator_version != GENERATOR_VERSION:
        # Refusing is the honest answer: this build cannot reproduce a dataset
        # generated by different algorithms, so claiming it could would make
        # the reproducibility guarantee meaningless.
        raise ValidationError(
            f"generator_version {spec.generator_version!r} is not supported by this build",
            details={"field": "generator_version", "supported": GENERATOR_VERSION},
        )
    if not spec.scenario_name.strip():
        raise ValidationError("scenario_name must not be empty", details={"field": "scenario_name"})
    if spec.seed < 0:
        raise ValidationError("seed must not be negative", details={"field": "seed"})
    if spec.start_virtual_time.tzinfo is None:
        raise ValidationError(
            "start_virtual_time must carry a timezone offset",
            details={"field": "start_virtual_time"},
        )
    for field_name, value, ceiling in (
        ("account_count", spec.account_count, limits.max_accounts_per_run),
        ("deal_count", spec.deal_count, limits.max_deals_per_run),
        ("max_open_positions", spec.max_open_positions, limits.max_open_positions_per_run),
    ):
        if value < 0:
            raise ValidationError(f"{field_name} must not be negative", details={"field": field_name})
        if value > ceiling:
            raise ValidationError(
                f"{field_name} exceeds the configured maximum",
                details={"field": field_name, "maximum": ceiling},
            )
    if not spec.symbols:
        raise ValidationError("at least one symbol is required", details={"field": "symbols"})
    if len(set(spec.symbols)) != len(spec.symbols):
        raise ValidationError("symbols must not contain duplicates", details={"field": "symbols"})
    for symbol in spec.symbols:
        symbol_spec(symbol)  # raises UNSUPPORTED_OPERATION or VALIDATION_FAILED
    acc.validate_money(spec.initial_balance_usd, field="initial_balance_usd", allow_negative=False)
    if spec.deal_count > 0 and spec.account_count == 0:
        raise ValidationError(
            "deal_count requires at least one account",
            details={"field": "account_count"},
        )
    if spec.execution_mode != "bulk_generate":
        raise ValidationError(
            f"execution_mode {spec.execution_mode!r} is not supported",
            details={"field": "execution_mode", "supported": ["bulk_generate"]},
        )


class OpenPositionIndex:
    """Open netting keys, selectable by index in a stable order.

    Two requirements pull in different directions here. Selection has to be
    cheap, because it happens on most of ~140k iterations. And it has to be
    *order-independent*: if selection depended on insertion order, then
    continuing a run via ``advance`` after a restart - which reloads this state
    from the database - would diverge from continuing it in the same process.

    Keeping the key list sorted satisfies both. ``bisect`` insert and remove
    are a memmove over a few thousand entries, and indexing is constant time.
    """

    __slots__ = ("_state", "_keys")

    def __init__(self, initial: dict[tuple[str, str], tuple[Side, Decimal]] | None = None) -> None:
        self._state: dict[tuple[str, str], tuple[Side, Decimal]] = dict(initial or {})
        self._keys: list[tuple[str, str]] = sorted(self._state)

    def __len__(self) -> int:
        return len(self._keys)

    def __contains__(self, key: tuple[str, str]) -> bool:
        return key in self._state

    def get(self, key: tuple[str, str]) -> tuple[Side, Decimal] | None:
        return self._state.get(key)

    def set(self, key: tuple[str, str], value: tuple[Side, Decimal]) -> None:
        if key not in self._state:
            insort(self._keys, key)
        self._state[key] = value

    def remove(self, key: tuple[str, str]) -> None:
        del self._state[key]
        position = bisect_left(self._keys, key)
        if position < len(self._keys) and self._keys[position] == key:
            self._keys.pop(position)

    def at(self, index: int) -> tuple[tuple[str, str], tuple[Side, Decimal]]:
        key = self._keys[index % len(self._keys)]
        return key, self._state[key]

    def as_dict(self) -> dict[tuple[str, str], tuple[Side, Decimal]]:
        return dict(self._state)


@dataclass(slots=True)
class GeneratorMirror:
    """The generator's view of mutable state.

    Either built up as intents are produced (a fresh run) or reloaded from the
    database (continuing an existing run via ``advance``).
    """

    accounts: list[str]
    open_positions: OpenPositionIndex
    prices: dict[str, tuple[Decimal, Decimal]]


class ExhaustedGenerationError(RuntimeError):
    """Raised when the deal target cannot be reached within the iteration bound.

    Reaching this means the action mix and the state constraints have
    deadlocked. Raising beats looping forever and beats quietly returning a
    short dataset that would fail an oracle comparison much later.
    """


class ScenarioGenerator:
    """Produces the intent stream for one scenario."""

    def __init__(self, spec: ScenarioSpec, *, max_open_positions: int) -> None:
        self._spec = spec
        self._rng = DeterministicRandom(spec.seed, spec.digest, version=spec.generator_version)
        self._symbols: tuple[str, ...] = tuple(spec.symbols)
        self._anchors = {
            symbol: _ANCHOR_PRICES.get(symbol, _DEFAULT_ANCHOR) for symbol in self._symbols
        }
        reachable = spec.account_count * len(self._symbols)
        configured = spec.max_open_positions or max_open_positions
        # The real ceiling is whichever is smaller: what the operator asked for
        # or how many distinct netting keys exist at all.
        self._max_open = min(configured, reachable) if reachable else 0
        self._mirror = GeneratorMirror(
            accounts=[], open_positions=OpenPositionIndex(), prices={}
        )

    # -- introspection -----------------------------------------------------

    @property
    def spec(self) -> ScenarioSpec:
        return self._spec

    @property
    def max_open_positions(self) -> int:
        return self._max_open

    @property
    def header_event_count(self) -> int:
        """Events produced before the trading phase begins.

        Used to translate ``committed_seq`` back into a trading-phase index
        when continuing a run.
        """
        return self._spec.account_count + len(self._symbols)

    def load_mirror(self, mirror: GeneratorMirror) -> None:
        self._mirror = mirror

    # -- phases ------------------------------------------------------------

    def header_intents(self) -> Iterator[Intent]:
        """Create every account, then seed an initial quote per symbol."""
        for ordinal in range(1, self._spec.account_count + 1):
            identifier = account_id(ordinal)
            self._mirror.accounts.append(identifier)
            yield CreateAccount(
                account_id=identifier,
                currency=ACCOUNT_CURRENCY,
                balance=self._spec.initial_balance_usd,
                credit=Decimal("0.00"),
            )
        for symbol in self._symbols:
            spec = symbol_spec(symbol)
            bid = acc.quantize_price(self._anchors[symbol], spec)
            ask = acc.quantize_price(bid + _SPREAD, spec)
            self._mirror.prices[symbol] = (bid, ask)
            yield UpdateMark(symbol=symbol, bid=bid, ask=ask)

    def trading_intents(
        self,
        *,
        start_index: int = 0,
        max_deals: int | None = None,
        max_events: int | None = None,
    ) -> Iterator[Intent]:
        """Yield trading-phase intents.

        Exactly one of ``max_deals`` / ``max_events`` normally bounds the
        stream; passing both stops at whichever is reached first.
        """
        if max_deals is None and max_events is None:
            max_deals = self._spec.deal_count
        deals = 0
        events = 0
        index = start_index
        # Generous, but finite. Ticks produce no deal, and with few netting
        # keys a large share of draws land on an empty key and tick, so the
        # bound has to allow for that without being unbounded.
        iteration_ceiling = ((max_deals or 0) * 12) + ((max_events or 0)) + 10_000
        iterations = 0
        while True:
            if max_deals is not None and deals >= max_deals:
                return
            if max_events is not None and events >= max_events:
                return
            iterations += 1
            if iterations > iteration_ceiling:
                raise ExhaustedGenerationError(
                    f"could not reach {max_deals} deals within {iteration_ceiling} iterations; "
                    f"produced {deals} deals over {events} events"
                )
            intent = self._next_intent(index)
            index += 1
            events += 1
            if isinstance(intent, (OpenPosition, IncreasePosition, ClosePosition)):
                deals += 1
            yield intent

    # -- decision ----------------------------------------------------------

    def _next_intent(self, index: int) -> Intent:
        action = self._rng.weighted_choice("action", index, _ACTION_WEIGHTS)
        open_positions = self._mirror.open_positions
        if action == "TICK" or not self._mirror.accounts:
            return self._tick(index)

        account = self._rng.choice("account", index, self._mirror.accounts)
        symbol = self._rng.choice("symbol", index, self._symbols)
        held = open_positions.get((account, symbol))

        if held is not None:
            if action == "INCREASE":
                return self._increase(index, account, symbol, held)
            return self._close(index, account, symbol, held)

        # Nothing open on the drawn netting key.
        if action != "INCREASE" and len(open_positions) < self._max_open:
            return self._open(index, account, symbol)

        # The open-position ceiling is reached (or the action needs an existing
        # position), so the draw is redirected to a key that *is* open rather
        # than discarded.
        #
        # Falling back to a tick here looks harmless but is not: when
        # `max_open_positions` is much smaller than accounts x symbols, almost
        # every draw lands on a closed key, so almost every iteration produces
        # no deal and the run cannot reach its deal target at all. Redirecting
        # keeps the deal rate independent of that ratio, and stays
        # deterministic because the open-key set is itself deterministic and
        # indexed in sorted order.
        if not len(open_positions):
            return self._tick(index)
        (account, symbol), held = open_positions.at(
            self._rng.uniform_int(
                "open_key", index, low=0, high=len(open_positions) - 1
            )
        )
        if action == "INCREASE":
            return self._increase(index, account, symbol, held)
        return self._close(index, account, symbol, held)

    def _tick(self, index: int) -> UpdateMark:
        symbol = self._rng.choice("tick_symbol", index, self._symbols)
        spec = symbol_spec(symbol)
        current_bid, _ = self._mirror.prices.get(
            symbol, (acc.quantize_price(self._anchors[symbol], spec), Decimal(0))
        )
        delta = self._rng.uniform_decimal(
            "tick_delta", index, low=-_TICK_DELTA, high=_TICK_DELTA, step=_TICK_GRID
        )
        anchor = self._anchors[symbol]
        with acc.calc_context():
            lower = anchor * (Decimal(1) - _PRICE_BAND)
            upper = anchor * (Decimal(1) + _PRICE_BAND)
            candidate = current_bid + delta
        bid = acc.quantize_price(min(max(candidate, lower), upper), spec, field="bid")
        ask = acc.quantize_price(bid + _SPREAD, spec, field="ask")
        self._mirror.prices[symbol] = (bid, ask)
        return UpdateMark(symbol=symbol, bid=bid, ask=ask)

    def _open(self, index: int, account: str, symbol: str) -> OpenPosition:
        spec = symbol_spec(symbol)
        side = self._rng.choice("side", index, (Side.BUY, Side.SELL))
        volume = self._rng.uniform_decimal(
            "volume", index, low=spec.min_lot, high=_MAX_OPEN_VOLUME, step=spec.lot_step
        )
        bid, ask = self._quote(symbol, spec)
        # You buy at the ask and sell at the bid. Using one price for both
        # would hand every position a free half-spread of profit.
        price = ask if side is Side.BUY else bid
        self._mirror.open_positions.set((account, symbol), (side, volume))
        return OpenPosition(
            account_id=account,
            symbol=symbol,
            side=side,
            volume_lots=volume,
            price=price,
            commission=acc.quantize_money(volume * _COMMISSION_PER_LOT, field="commission"),
            swap=Decimal("0.00"),
        )

    def _increase(
        self, index: int, account: str, symbol: str, held: tuple[Side, Decimal]
    ) -> Intent:
        spec = symbol_spec(symbol)
        side, volume = held
        added = self._rng.uniform_decimal(
            "increase_volume", index, low=spec.min_lot, high=_MAX_INCREASE_VOLUME, step=spec.lot_step
        )
        if volume + added > spec.max_lot:
            # Would breach the symbol's maximum lot. Close instead of emitting
            # an intent the engine is guaranteed to reject.
            return self._close(index, account, symbol, held)
        bid, ask = self._quote(symbol, spec)
        price = ask if side is Side.BUY else bid
        self._mirror.open_positions.set((account, symbol), (side, volume + added))
        return IncreasePosition(
            account_id=account,
            symbol=symbol,
            side=side,
            volume_lots=added,
            price=price,
            commission=acc.quantize_money(added * _COMMISSION_PER_LOT, field="commission"),
            swap=Decimal("0.00"),
        )

    def _close(
        self, index: int, account: str, symbol: str, held: tuple[Side, Decimal]
    ) -> ClosePosition:
        spec = symbol_spec(symbol)
        side, volume = held
        kind = self._rng.weighted_choice("close_kind", index, _CLOSE_KIND_WEIGHTS)
        if kind == "PARTIAL" and volume > spec.min_lot:
            close_volume = self._rng.uniform_decimal(
                "close_volume",
                index,
                low=spec.min_lot,
                high=volume - spec.min_lot,
                step=spec.lot_step,
            )
        else:
            close_volume = volume
        bid, ask = self._quote(symbol, spec)
        # Closing a long is a sell, which executes at the bid.
        price = bid if side is Side.BUY else ask
        swap = self._rng.uniform_decimal(
            "swap", index, low=_SWAP_LOW, high=_SWAP_HIGH, step=_SWAP_GRID
        )
        remaining = volume - close_volume
        if remaining == 0:
            self._mirror.open_positions.remove((account, symbol))
        else:
            self._mirror.open_positions.set((account, symbol), (side, remaining))
        return ClosePosition(
            account_id=account,
            symbol=symbol,
            volume_lots=close_volume,
            price=price,
            commission=acc.quantize_money(close_volume * _COMMISSION_PER_LOT, field="commission"),
            swap=acc.quantize_money(swap, field="swap"),
        )

    def _quote(self, symbol: str, spec: Any) -> tuple[Decimal, Decimal]:
        quote = self._mirror.prices.get(symbol)
        if quote is not None:
            return quote
        bid = acc.quantize_price(self._anchors[symbol], spec)
        ask = acc.quantize_price(bid + _SPREAD, spec)
        self._mirror.prices[symbol] = (bid, ask)
        return bid, ask


def spec_from_mapping(payload: dict[str, Any]) -> ScenarioSpec:
    """Build a spec from an already-validated API payload."""
    from ..canonical import parse_timestamp

    return ScenarioSpec(
        scenario_name=payload["scenario_name"],
        seed=int(payload["seed"]),
        start_virtual_time=parse_timestamp(payload["start_virtual_time"]),
        account_count=int(payload["account_count"]),
        deal_count=int(payload["deal_count"]),
        max_open_positions=int(payload.get("max_open_positions", 0)),
        symbols=tuple(payload["symbols"]),
        initial_balance_usd=acc.parse_decimal(
            payload["initial_balance_usd"], field="initial_balance_usd"
        ),
        generator_version=str(payload.get("generator_version", GENERATOR_VERSION)),
        execution_mode=str(payload.get("execution_mode", "bulk_generate")),
        fault_profile=str(payload.get("fault_profile", "none")),
    )


def default_symbols(symbols: Sequence[str] | None) -> tuple[str, ...]:
    from ..domain.models import DEFAULT_SYMBOLS

    return tuple(symbols) if symbols else DEFAULT_SYMBOLS
