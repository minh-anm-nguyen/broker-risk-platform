"""Render a scorecard from a what-if run. Nothing is filled in by hand.

The scorecard answers one question honestly: **what has actually been
demonstrated?** It keeps the five statuses separate rather than reducing them
to a percentage, because the difference between "passed", "nobody tested it"
and "this environment cannot test it" is the whole point - section 20 is
explicit that ``NOT_TESTED`` and ``NOT_SUPPORTED`` do not count as PASS.

It also prints the fault-combination axes from section 13.1 with the coverage
each one has, so an unexercised axis is visible instead of implied.

Usage::

    python scripts/generate_scorecard.py [--from artifacts] [--run RUN_ID]
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]

STATUS_ORDER = ("PASS", "FAIL", "NOT_CONCLUSIVE", "NOT_SUPPORTED", "NOT_TESTED")

#: The combination axes from section 13.1, with the case series that cover
#: each. Printed with their coverage so an axis nothing exercises shows up
#: rather than being absent from the report (WF2-R-11).
COMBINATION_AXES: dict[str, tuple[str, ...]] = {
    "source state": ("WF2-F", "WF2-J", "WF2-B"),
    "request lifecycle": ("WF2-G", "WF2-H"),
    "worker mode": ("WF2-F", "WF2-E", "WF2-O"),
    "data size": ("WF2-I", "WF2-M"),
    "network": ("WF2-C", "WF2-D"),
    "data anomaly": ("WF2-L", "WF2-I"),
    "consumer boundary": ("WF2-K", "WF2-Q"),
    "source identity": ("WF2-J", "WF2-B"),
    "load": ("WF2-M",),
    "combined faults": ("WF2-R",),
}

GATES: dict[str, str] = {
    "G0 - MVP correctness and async isolation": (
        "every P0 case is PASS or explicitly NOT_SUPPORTED"
    ),
    "G1 - resilience, recovery, security": (
        "no P0 case is FAIL, NOT_TESTED or NOT_CONCLUSIVE"
    ),
    "G2 - handoff to Project 03": "the K and Q series are PASS or NOT_SUPPORTED",
    "G3 - real SDK and performance hardening": (
        "the E series is PASS (needs an authorised SDK)"
    ),
}


def latest_run(root: Path) -> Path:
    runs = sorted(root.glob("*/what_if_results.json"), key=lambda path: path.parent.name)
    if not runs:
        raise SystemExit(f"no what-if results under {root}; run run_whatif_suite.py first")
    return runs[-1]


def series_of(case_id: str) -> str:
    return case_id.rsplit("-", 1)[0]


def render(results: dict[str, Any], manifest: dict[str, Any]) -> str:
    cases: list[dict[str, Any]] = results["cases"]
    lines: list[str] = []
    add = lines.append

    add("# Project 02 — MT5 Integration Connector: coverage scorecard")
    add("")
    add("Generated by `scripts/generate_scorecard.py`. Every figure below comes")
    add("from a test run; none of it is entered by hand (section 20).")
    add("")
    add("## Run")
    add("")
    add("| Field | Value |")
    add("|---|---|")
    for key in (
        "test_run_id",
        "git_sha",
        "generated_at",
        "python",
        "platform",
        "cpu_count",
        "worker_mode",
    ):
        if key in manifest:
            add(f"| {key} | {manifest[key]} |")
    add(f"| pytest exit code | {results.get('pytest_exit_code')} |")
    add(f"| source under test | {manifest.get('source', 'unknown')} |")
    add("")

    add("## What-if coverage by priority")
    add("")
    add("| Priority | " + " | ".join(STATUS_ORDER) + " | Total |")
    add("|---" * (len(STATUS_ORDER) + 2) + "|")
    totals: dict[str, dict[str, int]] = {
        priority: defaultdict(int) for priority in ("P0", "P1", "P2")
    }
    for case in cases:
        totals[case["priority"]][case["status"]] += 1
    for priority in ("P0", "P1", "P2"):
        row = totals[priority]
        count = sum(row.values())
        add(
            f"| {priority} | "
            + " | ".join(str(row.get(status, 0)) for status in STATUS_ORDER)
            + f" | {count} |"
        )
    add("")
    add("Statuses are not interchangeable. `NOT_TESTED` means no test in this")
    add("suite exercises the case; `NOT_SUPPORTED` means this build or this")
    add("environment cannot (an authorised Manager SDK, a network-layer proxy,")
    add("an 8-hour soak); `NOT_CONCLUSIVE` means a test ran and could not")
    add("decide. None of the three is a pass.")
    add("")

    add("## Release gates")
    add("")
    p0 = [case for case in cases if case["priority"] == "P0"]
    g0 = all(case["status"] in ("PASS", "NOT_SUPPORTED") for case in p0)
    g1 = not any(
        case["status"] in ("FAIL", "NOT_TESTED", "NOT_CONCLUSIVE") for case in p0
    )
    handoff = [
        case for case in cases if series_of(case["test_case_id"]) in ("WF2-K", "WF2-Q")
    ]
    g2 = all(case["status"] in ("PASS", "NOT_SUPPORTED") for case in handoff)
    native = [case for case in cases if series_of(case["test_case_id"]) == "WF2-E"]
    g3 = bool(native) and all(case["status"] == "PASS" for case in native)

    add("| Gate | Criterion | Result |")
    add("|---|---|---|")
    for (name, criterion), met in zip(GATES.items(), (g0, g1, g2, g3)):
        add(f"| {name} | {criterion} | {'MET' if met else 'NOT MET'} |")
    add("")
    if not g3:
        blocked = [case["test_case_id"] for case in native if case["status"] != "PASS"]
        add(
            f"G3 is blocked on {len(blocked)} native-SDK cases, which need an "
            "authorised Manager SDK, an approved endpoint and a documented field "
            "mapping. The driver refuses to run without them rather than returning "
            "synthesised data."
        )
        add("")

    add("## Coverage by series")
    add("")
    add("| Series | " + " | ".join(STATUS_ORDER) + " |")
    add("|---" * (len(STATUS_ORDER) + 1) + "|")
    by_series: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for case in cases:
        by_series[series_of(case["test_case_id"])][case["status"]] += 1
    for series in sorted(by_series):
        row = by_series[series]
        add(
            f"| {series} | "
            + " | ".join(str(row.get(status, 0)) for status in STATUS_ORDER)
            + " |"
        )
    add("")

    add("## Fault-combination axes (section 13.1)")
    add("")
    add("Reported per axis so an unexercised axis is visible rather than implied.")
    add("")
    add("| Axis | Cases | Passing | Coverage |")
    add("|---|---:|---:|---|")
    for axis, prefixes in COMBINATION_AXES.items():
        relevant = [
            case for case in cases if series_of(case["test_case_id"]) in prefixes
        ]
        passing = [case for case in relevant if case["status"] == "PASS"]
        ratio = len(passing) / len(relevant) if relevant else 0.0
        label = "none" if not passing else "partial" if ratio < 0.8 else "substantial"
        add(f"| {axis} | {len(relevant)} | {len(passing)} | {label} ({ratio:.0%}) |")
    add("")

    for status in ("FAIL", "NOT_CONCLUSIVE", "NOT_TESTED"):
        rows = [case for case in cases if case["status"] == status]
        if not rows:
            continue
        add(f"## {status} ({len(rows)})")
        add("")
        add("| Case | Priority | Reason |")
        add("|---|---|---|")
        for case in rows:
            reason = (case.get("reason_if_not_pass") or "").replace("|", "/")
            add(f"| {case['test_case_id']} | {case['priority']} | {reason} |")
        add("")

    unsupported = [case for case in cases if case["status"] == "NOT_SUPPORTED"]
    if unsupported:
        add(f"## NOT_SUPPORTED ({len(unsupported)})")
        add("")
        add("Each of these needs a capability this environment does not have. The")
        add("reason is stated so the gap is a list of requirements, not a mystery.")
        add("")
        add("| Case | Priority | Needs |")
        add("|---|---|---|")
        for case in unsupported:
            reason = (case.get("reason_if_not_pass") or "").replace("|", "/")
            add(f"| {case['test_case_id']} | {case['priority']} | {reason} |")
        add("")

    add("## What this scorecard does not claim")
    add("")
    add("* It is not evidence about the real MT5 Manager API. No authorised SDK,")
    add("  endpoint or credential was used, and the native driver refuses to run")
    add("  without them (design section 2).")
    add("* Integration evidence is against the Project 01 **contract double** in")
    add("  `tests/fakesim`, not the Project 01 service. Cross-service")
    add("  interoperability is untested.")
    add("* Benchmark numbers belong to the machine named above. They are")
    add("  measurements, not SLOs (section 0.3).")
    add("* Evidence levels do not add up: unit tests do not stand in for a")
    add("  process-kill test, and a contract double does not stand in for a")
    add("  vendor API (section 14.1).")
    add("")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--from", dest="source", type=Path, default=ROOT / "artifacts")
    parser.add_argument("--run", default=None, help="a specific test_run_id")
    parser.add_argument("--out", type=Path, default=None)
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args(argv)

    if args.run:
        results_path = args.source / args.run / "what_if_results.json"
        if not results_path.exists():
            raise SystemExit(f"no results for run {args.run}")
    else:
        results_path = latest_run(args.source)

    results = json.loads(results_path.read_text(encoding="utf-8"))
    manifest_path = results_path.parent / "manifest.json"
    manifest = (
        json.loads(manifest_path.read_text(encoding="utf-8"))
        if manifest_path.exists()
        else {}
    )

    text = render(results, manifest)
    out = args.out or results_path.parent / "scorecard.md"
    out.write_text(text, encoding="utf-8")
    if not args.quiet:
        print(text)
    print(f"scorecard written to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
