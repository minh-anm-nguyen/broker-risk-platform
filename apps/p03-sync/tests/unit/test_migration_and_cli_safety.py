"""Migration review gates and CLI safety rails (groups O, P, U)."""

from __future__ import annotations

import pathlib

import pytest

from trading_sync.cli import build_parser
from trading_sync.config import load_settings
from trading_sync.errors import ConfigurationError

pytestmark = pytest.mark.unit

MIGRATIONS = pathlib.Path(__file__).resolve().parents[2] / "migrations" / "versions"

#: Substrings searched for inside migration source, matched case-insensitively.
#: Alembic's autogenerate proposes these from a model diff, and an unreviewed
#: column removal is irreversible once deployed (WF3-172). Nothing here is
#: executed -- these are needle strings, not statements.
_DESTRUCTIVE_OPS = (
    "drop_column",
    "drop_constraint",
    "drop_index",
    "drop_table",
    "drop column",
    "drop table",
    "truncate",
    "delete from",
)


def _migration_texts() -> dict[str, str]:
    return {
        path.name: path.read_text(encoding="utf-8")
        for path in sorted(MIGRATIONS.glob("*.py"))
    }


def _upgrade_bodies() -> dict[str, str]:
    """Each revision's ``upgrade()`` source, excluding ``downgrade()``.

    A removal inside ``downgrade`` is the entire point of a downgrade; the gate
    below is about the forward path only.
    """
    bodies: dict[str, str] = {}
    for name, text in _migration_texts().items():
        start = text.find("def upgrade(")
        if start == -1:
            continue
        end = text.find("def downgrade(")
        bodies[name] = text[start : end if end != -1 else len(text)]
    return bodies


@pytest.mark.whatif("WF3-172")
def test_no_migration_destroys_data_on_the_forward_path() -> None:
    """The gate that stops an unreviewed autogenerated diff from shipping.

    Expand/contract is the intended pattern: add in one release, stop writing
    in the next, remove once nothing reads it. A migration that removes in a
    single step cannot be undone after it has run.
    """
    offenders = [
        (name, operation)
        for name, body in _upgrade_bodies().items()
        for operation in _DESTRUCTIVE_OPS
        if operation in body.lower()
    ]
    assert offenders == [], f"destructive operations on the upgrade path: {offenders}"


@pytest.mark.whatif("WF3-245")
def test_the_initial_migration_installs_the_deal_immutability_guard() -> None:
    """The guard is schema, not convention.

    Were a later migration to remove the trigger, application code could
    rewrite a commission again with nothing to stop it -- so its presence is
    asserted here as well as behaviourally in the integration suite.
    """
    texts = _migration_texts().values()
    assert any("trg_deals_immutable" in text for text in texts)
    assert any("deals_reject_mutation" in text for text in texts)
    assert any("BEFORE UPDATE OR DELETE ON deals" in text for text in texts)


@pytest.mark.whatif("WF3-184")
def test_the_application_role_is_never_granted_row_removal() -> None:
    """Retention is a separate audited task, not an ingestion privilege.

    Every GRANT is inspected, so widening it later fails here rather than
    being discovered when history goes missing.
    """
    grants = [
        line.strip()
        for text in _migration_texts().values()
        for line in text.splitlines()
        if "GRANT" in line and "sync_app" in line
    ]
    assert grants, "expected the migration to grant the application role its DML"
    assert any("SELECT, INSERT, UPDATE" in line for line in grants)
    for line in grants:
        lowered = line.lower()
        assert "delete" not in lowered, f"row removal granted to the app role: {line}"
        assert "truncate" not in lowered


@pytest.mark.whatif("WF3-188")
def test_approving_an_epoch_requires_an_explicit_reason() -> None:
    """A destructive-by-consequence action needs an audited justification.

    Approving a new epoch after a reset means a full re-read and a second copy
    of history. Requiring ``--reason`` makes that a decision somebody owns,
    recorded in ``sync_audit``.
    """
    parser = build_parser()
    with pytest.raises(SystemExit):
        parser.parse_args(["approve-epoch", "--epoch-id", "abc"])
    parsed = parser.parse_args(
        ["approve-epoch", "--epoch-id", "abc", "--reason", "operator rebootstrap"]
    )
    assert parsed.reason == "operator rebootstrap"


@pytest.mark.whatif("WF3-057")
def test_there_is_no_command_that_sets_a_watermark() -> None:
    """A watermark with no receipt chain behind it is an unverifiable claim.

    Catching a lagging source up by hand is the shortcut design 12.3 lists as
    forbidden, so there is deliberately no CLI surface for it -- and the
    publication guard would refuse it anyway.
    """
    parser = build_parser()
    commands = set(parser._subparsers._group_actions[0].choices)  # noqa: SLF001
    assert commands == {"enroll", "approve-epoch", "run", "status", "epochs"}
    for forbidden in ("set-watermark", "reset", "wipe", "force-publish"):
        assert forbidden not in commands


@pytest.mark.whatif("WF3-246")
def test_the_scan_budget_is_validated_against_the_declared_cursor_ttl() -> None:
    """A source TTL change must not silently invalidate the scan budget.

    The TTL is configuration and the budget is checked against it, so a
    contract change surfaces as a startup error rather than as scans that
    mysteriously begin failing at their terminal page.
    """
    ok = load_settings(
        database_url="postgresql+asyncpg://u@h/db",
        source={"cursor_ttl_seconds": 900},
        sync={"scan_max_duration_seconds": 720},
    )
    assert ok.sync.scan_max_duration_seconds < ok.source.cursor_ttl_seconds

    with pytest.raises(ConfigurationError):
        load_settings(
            database_url="postgresql+asyncpg://u@h/db",
            # The source shortened its TTL; the old budget no longer fits.
            source={"cursor_ttl_seconds": 300},
            sync={"scan_max_duration_seconds": 720},
        )
